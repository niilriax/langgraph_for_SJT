"""Prompt for expanding a facet's behavior evidence into a situation space."""


EXPANSION_PROMPT = """
为一个人格 facet 的全部行为证据，扩展出紧凑、有理论依据、适合目标人群的情境空间。不要写题干、选项、分数、评审、理由或流程元数据。

任务与输入
────────
- facet_profile：目标 facet 的含义与方向，以及它与相邻 facet、能力、道德、社会赞许性的边界。机制涉及的心理过程必须落在这个范围内。
- behavior_evidence：要被激活的可观察行为差异和抽象层级。每个 behavior_id 对应一条证据。
- theory_notes（如有）：哪些情境线索能激活该行为，哪些竞争目标相关，为什么会出现不同表现。
- target_population：限定领域、人物关系、权限与资源、事件频率与风险、文化与发展阶段。情境须是这类人日常里常见的，当事人有真实的选择权，不需要专业知识，不出现罕见的紧急情况或极端不当行为。
- 机制必须能由 facet_profile、theory_notes 或行为证据直接推出，不要因为“一般来说合理”就编造心理冲突。
- 所有文字字段用 output_language 指定的语言书写。

机制怎么写
────────
- 每个 behavior_id 返回一份扩展，沿用原 ID，不新造 ID。每份含 1–4 个激活机制，数量随证据的复杂程度而定。
- 一个机制写成一句话，包含四点：
  1. 与特质相关的情境线索；
  2. 两个在日常中都正当的竞争目标或偏好；
  3. 为什么情境留有选择余地；
  4. 行为差异通过什么可观察的决策模式表现出来。
- 机制要说明“何时、为什么会表现出该行为”，不能只复述高低分两端。
- 同一 behavior_id 下的机制必须实质不同：线索、竞争目标、保留选择余地的原因、可观察的选择，至少有一项明显不同。只换地点、人物、人物关系、组织类型、学科或事件措辞的，合并成一个。宁可保留一个有依据的机制，也不要几个语义重复的。

两条路都要合理
────────
这一段决定情境能否区分特质，而不是区分对错或能力。
- 每个机制都要给目标行为差异留出表现的机会。
- 用弱情境：没有规则明确要求某种做法；没有明显违法、危险、残忍、欺骗或不负责的选项；后果有意义但不极端；当事人有现实的选择；两条路都有实际或心理上的理由。
- 不用强情境：规则明确要求一种做法；重罚使人别无选择；安全或紧急情况决定了反应；一条路明显道德、另一条明显有害；一条路需要无能、鲁莽或恶意。
- 两个竞争目标都必须正当。不要拿目标特质去对立疏忽、不诚实、残忍、无能或一般的不负责。
- 不要把目标差异写成：合法与违法、守规与违规、服从与反抗、道德与不道德、助人与伤害、能力强与能力弱、情绪成熟与失调、被认可与被谴责。来源证据里若出现作弊、钻空子、剥削、攻击、不负责或伤害，只保留与目标 facet 直接相关的过程，不要把不当行为本身当作情境冲突；也不要为了让这类来源例子变得可用，去编造证据和理论都不支持的过程。
- 机制用目标 facet 来解释，应比用其他人格 facet、一般能力、社交技能、专业知识、道德或情境要求来解释更有力。
- 差异要用当事人可观察的做法来定义：说了什么、披露或隐瞒什么、强调什么、选了什么、推迟什么、发起什么、继续什么。不要用无法观察的动机，如真心与否、隐藏的自私、恶意、无意识目标、想操纵别人。

情境条目怎么写
────────
- 每个机制含一个或多个情境条目。整个 facet 的情境条目总数必须恰好等于 required_situation_count（不是每个机制各自的配额）。不要靠改写措辞造出重复情境来凑数。
- 每个条目恰好包含：domain、actor_relation、event_class；提供了 behavior_manifestations 和 trigger_types 时，还要有 manifestation_ids 和 trigger_id。
- domain：必须原样取自 life_domains。遵守 domain_coverage：整个 facet 至少用 min_distinct_domains 个不同领域，每个领域最多 max_situations_per_domain 条。不要把大多数情境放进同一个场景。
- actor_relation：说明关系，以及与心理相关的角色特征，不添加不必要的个人细节。
- event_class：写出与特质相关的线索和决策张力，不能只是活动名称（如“求助”“小组合作”“参加活动”“给反馈”“化解冲突”）。要抽象到能支持之后的多道题，又要具体到保留激活线索、竞争目标、选择余地和要区分的可观察差异。
- 同一机制下的情境条目，要在触发事件上不同，不能只换地点、人物或措辞。例：在食堂洒了饮料和在课上碰倒杯子是同一个事件；在课上说错话和走错教室是不同的事件。
- manifestation_ids：behavior_manifestations 按 behavior_id 列出高分和低分的具体行为。每个情境条目必须让所属 behavior_id 的至少一个高分行为和一个低分行为成为现实可选的做法，并把它们的 manifestation_id 写进 manifestation_ids。让情境尽量覆盖更多不同的行为。
- trigger_id：必须取自 trigger_types，且该触发类型的 behavior_ids 包含本条目的 behavior_id；event_class 要通过这条路径激活 facet。遵守 trigger_coverage：整个 facet 至少用 min_distinct_triggers 种触发类型，每种最多 max_situations_per_trigger 条。不要让某一种情节（例如“出了差错，大家都看着你”）占据整个 facet。

输出
────────
只返回要求的结构化对象，不要附带说明、解释、引用、构念边界、分数、评审或对象之外的文字。
""".strip()
